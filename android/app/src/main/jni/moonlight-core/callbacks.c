int BridgeDrSetup(int videoFormat, int width, int height, int redrawRate, void* context, int drFlags) {
    JNIEnv* env = GetThreadEnv();
    int err;

    err = (*env)->CallStaticIntMethod(env, GlobalBridgeClass, BridgeDrSetupMethod, videoFormat, width, height, redrawRate);
    if ((*env)->ExceptionCheck(env)) {
        // This is called on a Java thread, so it's safe to return
        return -1;
    }
    else if (err != 0) {
        return err;
    }

    // Use a 32K frame buffer that will increase if needed
    jbyteArray localBuffer = (*env)->NewByteArray(env, 32768);
    if (localBuffer == NULL) {
        (*env)->ExceptionClear(env);
        (*env)->CallStaticVoidMethod(env, GlobalBridgeClass, BridgeDrCleanupMethod);
        CallFailed(env);
        return -1;
    }

    DecodedFrameBuffer = (*env)->NewGlobalRef(env, localBuffer);
    (*env)->DeleteLocalRef(env, localBuffer);
    if (DecodedFrameBuffer == NULL) {
        (*env)->CallStaticVoidMethod(env, GlobalBridgeClass, BridgeDrCleanupMethod);
        CallFailed(env);
        return -1;
    }

    return 0;
}

